import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const cache=new Map();
function moduleUrl(name){
  if(cache.has(name))return cache.get(name);
  let js=ts.transpileModule(readFileSync(new URL(`../src/${name}.ts`,import.meta.url),'utf8'),
    {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
  js=js.replace(/from ["']\.\/([^"']+)["']/g,(_,dep)=>`from "${moduleUrl(dep)}"`);
  const url=`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`;cache.set(name,url);return url;
}
const z=await import(moduleUrl('zone-features')), b=await import(moduleUrl('board'));
const forest=z.restoreZoneFeatures();forest.marks=[6,7];
assert.equal(z.resolveZoneMatches('forest',forest,7,[{r:0,c:6}],0).wood,0);
assert.equal(z.resolveZoneMatches('forest',forest,7,[{r:0,c:6}],0).wood,0);
const snow=z.restoreZoneFeatures();snow.marks=[6,7];
assert.deepEqual(z.resolveZoneMatches('snow',snow,7,[{r:0,c:5}],0).removed,[6]);
assert.deepEqual(snow.marks,[7],'adjacency must not wrap across a row');
const dungeon=z.restoreZoneFeatures();let gems=0;
for(let i=0;i<12;i++)gems+=z.resolveZoneMatches('dungeon',dungeon,7,[],3).gems;
assert.equal(gems,9,'three caches at most, no extra payout after completion');
assert.equal(dungeon.caches,3);
